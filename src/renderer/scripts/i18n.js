let currentLang = localStorage.getItem('matra_lang') || 'en';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (lang !== 'bn' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('matra_lang', lang);
  applyTranslations();
}

export function toggleLanguage() {
  setLanguage(currentLang === 'bn' ? 'en' : 'bn');
}

export function applyTranslations() {
  const langText = currentLang === 'bn' ? 'English' : 'বাংলা';
  const langIndicator = document.getElementById('lang-indicator');
  if (langIndicator) {
    langIndicator.textContent = langText;
  }

  const dict = translations[currentLang];
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  document.documentElement.setAttribute('lang', currentLang);
}
